def main() -> None:
    with MISSING_PATH.open(encoding="utf-8") as f:
        missing = json.load(f)
    with OUT_PATH.open(encoding="utf-8") as f:
        existing = json.load(f)

    missing_set = set(missing)
    new_set = set(NEW)
    if missing_set != new_set:
        only_missing = sorted(missing_set - new_set)
        only_new = sorted(new_set - missing_set)
        raise SystemExit(
            f"Key mismatch: only_in_missing={only_missing[:20]} "
            f"only_in_NEW={only_new[:20]} "
            f"counts={len(only_missing)}/{len(only_new)}"
        )

    # Preserve all existing keys unchanged; add NEW
    merged = dict(existing)
    for key, val in NEW.items():
        if key in merged:
            raise SystemExit(f"Refusing to overwrite existing key: {key}")
        for lang in ("uk", "be", "kk"):
            if not str(val.get(lang, "")).strip():
                raise SystemExit(f"Empty {lang} for {key}")
        merged[key] = {"uk": val["uk"], "be": val["be"], "kk": val["kk"]}

    # Stable-ish order: existing order first, then new keys in missing_keys order
    ordered: dict[str, dict[str, str]] = {}
    for k in existing:
        ordered[k] = merged[k]
    for k in missing:
        ordered[k] = merged[k]

    with OUT_PATH.open("w", encoding="utf-8") as f:
        json.dump(ordered, f, ensure_ascii=False, indent=1)
        f.write("\n")

    # Verification
    with OUT_PATH.open(encoding="utf-8") as f:
        final = json.load(f)
    with MISSING_PATH.open(encoding="utf-8") as f:
        missing2 = json.load(f)

    for key in missing2:
        assert key in final, key
        for lang in ("uk", "be", "kk"):
            assert final[key].get(lang, "").strip(), f"{key}.{lang}"

    print(f"existing_before={len(existing)}")
    print(f"missing_keys={len(missing2)}")
    print(f"added={len(NEW)}")
    print(f"final_total={len(final)}")
    print(f"union_expected={len(set(existing) | set(missing2))}")
    assert len(final) == len(set(existing) | set(missing2))
    print("OK")


if __name__ == "__main__":
    main()
